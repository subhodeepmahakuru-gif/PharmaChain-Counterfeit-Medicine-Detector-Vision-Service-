
"""
predict.py

PharmaChain - Member 4: Medicine Packaging Detector

Loads a trained ResNet-18 model and classifies one medicine
packaging image.

"""

import argparse
import os
import sys

import torch
import torch.nn as nn

from PIL import Image, UnidentifiedImageError

from torchvision import models, transforms


# ==========================================
# CONFIGURATION
# ==========================================

MEAN = [0.485, 0.456, 0.406]
STD = [0.229, 0.224, 0.225]

DEFAULT_IMAGE_SIZE = 224

DEFAULT_THRESHOLD = 0.70


# ==========================================
# CLASSIFIER
# ==========================================

class Classifier:

    def __init__(
        self,
        path="model.pt",
        threshold=DEFAULT_THRESHOLD
    ):

        # Check model file
        if not os.path.isfile(path):
            raise FileNotFoundError(
                f"Model file not found: {path}"
            )

        if not 0.0 <= threshold <= 1.0:
            raise ValueError(
                "Threshold must be between 0 and 1."
            )

        # Select CPU or GPU
        self.device = torch.device(
            "cuda" if torch.cuda.is_available() else "cpu"
        )

        self.threshold = threshold

        # Load checkpoint
        try:
            try:
                checkpoint = torch.load(
                    path,
                    map_location=self.device,
                    weights_only=True
                )
            except TypeError:
                # Compatibility with older PyTorch versions
                checkpoint = torch.load(
                    path,
                    map_location=self.device
                )

        except Exception as error:
            raise RuntimeError(
                f"Unable to load model checkpoint: {error}"
            ) from error

        # Validate checkpoint
        if not isinstance(checkpoint, dict):
            raise ValueError(
                "Invalid model checkpoint format."
            )

        if "state_dict" not in checkpoint:
            raise ValueError(
                "Checkpoint does not contain state_dict."
            )

        if "class_names" not in checkpoint:
            raise ValueError(
                "Checkpoint does not contain class_names."
            )

        self.class_names = checkpoint["class_names"]

        if (
            not isinstance(self.class_names, list)
            or len(self.class_names) != 2
            or set(self.class_names) != {"genuine", "counterfeit"}
        ):
            raise ValueError(
                "Expected exactly two classes: "
                "'genuine' and 'counterfeit'."
            )

        # Get image size from checkpoint
        image_size = checkpoint.get(
            "image_size",
            checkpoint.get("img_size", DEFAULT_IMAGE_SIZE)
        )

        if not isinstance(image_size, int) or image_size <= 0:
            raise ValueError("Invalid image size in checkpoint.")

        # Create ResNet-18 architecture
        self.model = models.resnet18(weights=None)

        # Support both simple Linear and Sequential classification heads
        saved_state = checkpoint["state_dict"]

        if "fc.1.weight" in saved_state:
            # Sequential head with Dropout + Linear
            in_features = saved_state["fc.1.weight"].shape[1]

            self.model.fc = nn.Sequential(
                nn.Dropout(p=0.3),
                nn.Linear(
                    in_features,
                    len(self.class_names)
                )
            )

        else:
            # Standard Linear classification head
            in_features = self.model.fc.in_features

            self.model.fc = nn.Linear(
                in_features,
                len(self.class_names)
            )

        # Load trained weights
        try:
            self.model.load_state_dict(saved_state, strict=True)

        except RuntimeError as error:
            raise RuntimeError(
                "Model architecture does not match the checkpoint. "
                "Use the model.pt generated by the matching training script. "
                f"Details: {error}"
            ) from error

        # Move model to selected device
        self.model = self.model.to(self.device)

        self.model.eval()

        # Image preprocessing
        self.transform = transforms.Compose([

            transforms.Resize(
                (image_size, image_size)
            ),

            transforms.ToTensor(),

            transforms.Normalize(
                MEAN,
                STD
            )

        ])

        print("Model loaded successfully.")
        print("Device:", self.device)
        print("Classes:", self.class_names)


    # ======================================
    # IMAGE PREDICTION
    # ======================================

    def predict(self, image):

        if not isinstance(image, Image.Image):
            raise TypeError(
                "Input must be a PIL Image."
            )

        # Convert image to RGB
        image = image.convert("RGB")

        # Preprocess image
        tensor = self.transform(image)

        # Add batch dimension
        tensor = tensor.unsqueeze(0)

        tensor = tensor.to(self.device)

        # Run prediction
        with torch.inference_mode():

            outputs = self.model(tensor)

            probabilities = torch.softmax(
                outputs,
                dim=1
            )[0]

        # Get highest scoring class
        best_index = int(
            torch.argmax(probabilities).item()
        )

        confidence = float(
            probabilities[best_index].item()
        )

        predicted_label = self.class_names[best_index]

        # Convert probabilities into readable scores
        scores = {
            name: round(float(probability), 4)
            for name, probability in zip(
                self.class_names,
                probabilities.cpu().tolist()
            )
        }

        # Uncertainty handling
        if confidence < self.threshold:

            result = "unable_to_verify"

        else:

            result = predicted_label

        return {

            "prediction": result,

            "model_prediction": predicted_label,

            "confidence": round(confidence, 4),

            "threshold": self.threshold,

            "scores": scores,

            "authentication_status": (
                "NOT_AUTHENTICATED"
            ),

            "message": (
                "Image classification is not proof of "
                "medicine authenticity. Verify the product "
                "using manufacturer or authorized supply-chain records."
            )

        }


# ==========================================
# MAIN FUNCTION
# ==========================================

def main():

    parser = argparse.ArgumentParser(
        description="Classify medicine packaging using ResNet-18."
    )

    parser.add_argument(
        "image",
        help="Path to the medicine packaging image"
    )

    parser.add_argument(
        "--model",
        default="model.pt",
        help="Path to trained model checkpoint"
    )

    parser.add_argument(
        "--threshold",
        type=float,
        default=DEFAULT_THRESHOLD,
        help="Minimum model confidence for a class prediction"
    )

    args = parser.parse_args()

    # Validate threshold
    if not 0.0 <= args.threshold <= 1.0:
        parser.error(
            "Threshold must be between 0 and 1."
        )

    # Validate image path
    if not os.path.isfile(args.image):
        sys.exit(
            f"Error: Image file not found: {args.image}"
        )

    try:

        # Load model
        classifier = Classifier(
            path=args.model,
            threshold=args.threshold
        )

        # Open image
        with Image.open(args.image) as img:

            img.load()

            result = classifier.predict(img)

        # Display result
        print("\n================================")
        print("PHARMACHAIN PREDICTION RESULT")
        print("================================")

        print(
            "Image:",
            os.path.basename(args.image)
        )

        print(
            "Prediction:",
            result["prediction"]
        )

        print(
            "Model prediction:",
            result["model_prediction"]
        )

        print(
            "Confidence:",
            result["confidence"]
        )

        print("\nClass scores:")

        for name, score in result["scores"].items():

            print(
                f"{name}: {score:.4f}"
            )

        print(
            "\nAuthentication status:",
            result["authentication_status"]
        )

        print(
            "\nMessage:",
            result["message"]
        )

        print("\n================================")

    except (
        UnidentifiedImageError,
        OSError
    ) as error:

        sys.exit(
            f"Error opening image: {error}"
        )

    except (
        FileNotFoundError,
        ValueError,
        RuntimeError,
        TypeError
    ) as error:

        sys.exit(
            f"Prediction error: {error}"
        )


# ==========================================
# PROGRAM ENTRY POINT
# ==========================================

if __name__ == "__main__":
    main()
